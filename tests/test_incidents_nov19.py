"""Прод 18–19.11 (Макс 19.11: «ссылки не присылаются на оплату»): после «на мой аккаунт?» клиент выбирал вариант
ответом на предложение одного варианта или ценой, а заказ снимался — ушло «Вот реквизиты для оплаты:» без ссылки;
обещание реквизитов без заказа — к Максу, а не клиенту."""
from services.dialog import brain
from services.dialog.brain import REQ_PROMISE, own_unclear, variant_chosen

# GNS 19.11 u2i-32Uz…: «на свой аккаунт» → 14 мес (оба варианта) → «если на мой аккаунт, вы сами активируете?» →
# «14 мес на личный — 9 690 ₽. Оформляем?» → «Да оформляемся»
PERSONAL_CHAT = [
    ("client", "Хочу приобрести подписку ultimate на 19 месяцев, на свой аккаунт. Сколько будет стоить?"),
    ("seller", "Подключаем через дополнительный аккаунт с подпиской. На личный аккаунт 19 мес не делаем. Какой вариант подходит?"),
    ("client", "14 месяцев"),
    ("seller", "14 мес через дополнительный аккаунт — 5 090 ₽ (для Вас со скидкой за отзыв — 4 990 ₽), на Ваш личный "
               "аккаунт — 9 690 ₽. Какой вариант подходит?"),
    ("client", "Объясните по подробнее на дополнительный аккаунт это как?"),
    ("seller", "Подключаем на Вашу консоль отдельный аккаунт… На личный аккаунт — 9 690 ₽ за 14 мес."),
    ("client", "Если на мой аккаунт, вы сами активируете?"),
    ("seller", "На личный аккаунт подключаем сами, удалённо. 14 мес на личный аккаунт — 9 690 ₽. Оформляем?"),
    ("client", "Да оформляемся"),
]
# GNS 19.11 u2i-gig~…: «нужен свой аккаунт» → «за 5090» → оба варианта → «За 4990» → «Оформляем через доп» → «Давайте.»
MAIN_CHAT = [
    ("client", "Нужен свой аккаунт. И есть ли подписка на ПК и Xbox?"),
    ("seller", "На консоль и на ПК сразу подписка работает только на Вашем личном аккаунте."),
    ("client", "Давайте вариант на 14 месяцев за 5090. Какая игра в 🎁?"),
    ("seller", "14 мес через дополнительный аккаунт — 5 090 ₽ (для Вас со скидкой за отзыв — 4 990 ₽), на Ваш личный "
               "аккаунт — 9 690 ₽. Какой вариант подходит?"),
    ("client", "За 4990"),
]


def clients(h):
    return [t for who, t in h if who == "client"]


def test_personal_offer_accepted():
    """Предложен один вариант (личный) и «да» — заказ на личный оформляется, на доп. — нет."""
    assert own_unclear(clients(PERSONAL_CHAT))   # сам клиент «личный» не говорил
    assert variant_chosen(PERSONAL_CHAT, {"product": "personal", "months": 14, "price": 9690}) == "personal"
    assert variant_chosen(PERSONAL_CHAT) == "personal"


def test_price_names_variant():
    """«За 4990» — цена доп. аккаунта со скидкой: вариант выбран."""
    order = {"product": "console", "months": 14, "price": 4990}
    assert variant_chosen(MAIN_CHAT, order) == "main"
    # и «Давайте.» на «Оформляем: 14 мес через дополнительный аккаунт за 4 990 ₽»
    h = MAIN_CHAT + [("seller", "Оформляем: 14 мес через дополнительный аккаунт за 4 990 ₽."), ("client", "Давайте.")]
    assert variant_chosen(h, order) == "main"


def test_both_variants_still_unclear():
    """Оба варианта в последнем ответе и «давайте» без цены — вариант не выбран, как 18.11."""
    h = MAIN_CHAT[:4] + [("client", "Давайте")]
    assert variant_chosen(h, {"product": "console", "months": 14, "price": 4990}) is None
    assert variant_chosen(h, {"product": "personal", "months": 14, "price": 9690}) is None
    assert variant_chosen([("client", "12")]) is None   # «на мой аккаунт?» не было


def test_req_promise():
    for t in ("Вот реквизиты для оплаты:",
              "Оформляем: 14 мес через дополнительный аккаунт за 4 990 ₽. Ссылку на оплату пришлём — с любого банка.",
              "Ссылка на оплату должна была прийти отдельным сообщением — посмотрите чуть выше.",
              "Ссылка на оплату придёт отдельным сообщением — откройте её на телефоне.",
              "Реквизиты придут отдельным сообщением.", "Реквизиты для оплаты — по ссылке выше 👆"):
        assert REQ_PROMISE.search(t), t
    for t in ("Инструкцию по подключению пришлём после оплаты.", "Оплата только по ссылке СБП — с любого российского банка.",
              brain.IP_ONLY_REPLY, "Оплата проверится автоматически — доступ пришлю сразу после неё 🙏",
              "Цены — в сообщении выше 👆", "Как оплатите — пришлите, пожалуйста, скрин 🙏"):
        assert not REQ_PROMISE.search(t), t


PRICES = {"console": {12: 4290, 14: 5090}, "pc": {10: 1800}, "personal": {12: 8490, 14: 9690}}


def test_price_choice():
    """«За 4990» на строку с обоими вариантами — заказ на доп. аккаунт (прод 19.11: «Уточню и напишу Вам»)."""
    assert brain.price_choice(MAIN_CHAT, PRICES) == {"product": "console", "months": 14, "price": 5090}
    assert brain.price_choice(MAIN_CHAT[:-1] + [("client", "за 9690")], PRICES)["product"] == "personal"
    assert brain.price_choice(MAIN_CHAT[:-1] + [("client", "а почему 4990?")], PRICES) is None
    assert brain.price_choice(MAIN_CHAT[:-1] + [("client", "давайте")], PRICES) is None   # цены нет — не ясно
    # LLM заполнила цену прайса 5 090, клиент назвал со скидкой — вариант всё равно выбран
    assert variant_chosen(MAIN_CHAT, {"product": "console", "months": 14, "price": 5090}) == "main"


def test_req_promise_punctuation():
    assert REQ_PROMISE.search("Оплата переводом по реквизитам — пришлём их в чат.")
    assert not REQ_PROMISE.search("После оплаты по реквизитам пришлём инструкцию.")
