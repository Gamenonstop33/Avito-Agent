def guard_reply(reply: str, new: bool, price: str = "", client_said: str = "", found: dict | None = None) -> str:
    """Страховка там, где LLM ошибается упорно (прогоны 07.10): подарок/розыгрыш покупавшему, вопрос о платформе
    (срок в обоих разделах — без цены; только в одном — без вопроса), подключение до оплаты, «реквизиты те же»."""
    if mask(reply) != reply:   # почта, пароль, код, телефон, карта: доступы и реквизиты даёт только код, не LLM
        reply = " ".join(s for s in _sentences(reply) if mask(s) == s)
    if not new and ("{подарки}" in reply or (re.search(r"(?i)подар|розыгрыш", reply) and "перв" not in reply)):
        return GIFT_FIRST_ONLY
    if HUMAN_CLAIM.search(reply):
        return random.choice(BOT_JOKES)
    hits = [g for v in (found or {}).values() for g in v]
    if hits and re.search(r"(?i)русск", reply) and not any(g.get("ru") for g in hits):   # без пометки — не утверждаем
        reply = " ".join(s if not re.search(r"(?i)русск", s) else RU_UNKNOWN for s in _sentences(reply))
        reply = " ".join(dict.fromkeys(_sentences(reply)))
    if BANK_NAME.search(reply):   # банк выдаётся по кругу вместе с реквизитами заказа — заранее не называем
        reply = " ".join(s for s in _sentences(reply) if not BANK_NAME.search(s)) or PAY_BANK_LATER
    parts = _sentences(reply)
    c, p = price_terms(price)
    named = {int(m) for m in re.findall(r"(\d+)\s*мес", reply)}
    if ("₽" in reply and named & c & p and price and not PLATFORM_Q.search(reply)
            and not PLATFORM_WORDS.search(client_said)   # срок есть и там, и там, а клиент платформу не называл
            and not re.search(r"(?i)личн|ваш\w* аккаунт|сво\w* аккаунт|мо\w* аккаунт", reply + " " + client_said)):
        return "На консоль или на ПК?"
    if PLATFORM_Q.search(reply) and "₽" in reply:
        c, p = price_terms(price)
        months = {int(m) for m in re.findall(r"(\d+)\s*мес", reply)}
        if months and c and p and not months & c & p:   # срок только для одной платформы — спрашивать нечего
            parts = [s for s in parts if not PLATFORM_Q.search(s)] or parts
        else:                                            # срок есть и там, и там — сначала вопрос, без цены
            parts = [s for s in parts if "₽" not in s] or parts
    parts = [s for s in parts if not PAY_LATER.search(s) and not SAME_REQUISITES.search(s)] or parts
    return reply if len(parts) == len(_sentences(reply)) else " ".join(parts)


def render_reply(reply: str, price: str, first: bool = False, new: bool = True, personal: str = "",
                 gifts: str = "") -> str:
    """first — первый ответ в чате: приветствие + прайс + вопрос о сроке, затем ответ на вопрос клиента.
    gifts — список игр в подарок на выбор (метка {подарки}), только новому клиенту."""
    parts = [GREETING, price, PRICE_TAIL if new else PRICE_TAIL_RETURNING] if first else []
    if reply and first:   # вопрос о сроке и строка о скидке уже в приветствии — вырезаем только их, остальное оставляем
        reply = re.sub(r"(?i)(вас\s+)?на\s+какой\s+срок\s+(вас\s+)?(интересует|нужн\w*)(\s+подписка)?\s*\?", "", reply)
        if new:
            reply = re.sub(r"(?i)для\s+новых\s+клиентов\s+(делаем\s+)?скидк\w*\s+за\s+отзыв\s*🌟?[.!]?", "", reply)
        reply = re.sub(r"[ \t]{2,}", " ", reply).strip()
    if reply:
        for mark, block in (("{прайс_личный}", personal or "[прайс на личный аккаунт]"), ("{прайс}", price),
                            ("{подарки}", gifts)):
            # прайс — всегда отдельным абзацем: «срок от 4 мес: {прайс_личный}. Скидка…» не склеится с ценами
            reply = re.sub(rf"[ \t]*{re.escape(mark)}[ \t]*[.,;]?[ \t]*", lambda _: f"\n\n{block}\n\n", reply)
        parts.append(reply)
    return re.sub(r"\n{3,}", "\n\n", "\n\n".join(parts)).strip()


DISCOUNT_MAX = 100


def foreign_prices(reply: str, prices: set[int], new: bool = True, discountable: set[int] | None = None) -> list[int]:
    """Цены в ответе LLM (до подстановки прайса), которых нет в прайсе — признак выдумки.
    Новому клиенту допустима цена из прайса минус до 100 ₽ (скидка за отзыв) — только для discountable
    (по умолчанию все; личный аккаунт без скидки)."""
    discountable = prices if discountable is None else discountable
    num = r"(\d{1,3}(?:\s\d{3})+|\d+)"
    found = [int(re.sub(r"\s", "", m)) for m in
             re.findall(num + r"\s*(?:₽|р\.|руб)", reply) + re.findall(r"(?i)\bза\s+" + num + r"(?!\s*(?:мес|дн|мин|час))",
                                                                      reply)]

    def ok(x: int) -> bool:
        return x in prices or x <= DISCOUNT_MAX or (new and any(p - DISCOUNT_MAX <= x <= p for p in discountable))
    return [x for x in dict.fromkeys(found) if not ok(x)]


