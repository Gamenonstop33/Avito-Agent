def term_product(months: int, said: str, prices: dict[str, dict[int, int]], known: str | None = None) -> str | None:
    """Чей это срок: личный (клиент о нём говорил), прошлая покупка, названная платформа или единственный раздел
    прайса с этим сроком. Не ясно — None."""
    if (PERSONAL_WORDS.search(said) or BOTH_PLATFORMS.search(said)) and months in prices.get("personal", {}):
        return "personal"
    console, pc = bool(CONSOLE_WORDS.search(said)), bool(PC_WORDS.search(said))
    for product, ok in ((known, True), ("console", console and not pc), ("pc", pc and not console)):
        if product and ok and months in prices.get(product, {}):
            return product
    owners = [p for p in ("console", "pc") if months in prices.get(p, {})]
    return owners[0] if len(owners) == 1 else None


def upsell_overreach(history: list[tuple[str, str]], months: int) -> str | None:
    """LLM оформила срок из допродажи, который клиент не выбирал (стенд 22.10: на «Оформляем на 20 мес или оставим
    12?» клиент — «хочу Hogwarts Legacy в подарок», счёт ушёл на 20 мес). Тогда — вопрос допродажи ещё раз, иначе None."""
    tail = []
    for who, t in reversed(history[-6:]):
        if who == "seller" and UPSELL_MARK in t:
            offered = offered_terms(t)
            if not offered or months not in offered[1:]:
                return None   # свой срок или не из предложенных — не допродажа
            said = " ".join(reversed(tail))
            named = {int(m.group(1)) if m.group(1) else 6 if m.group(2) else 12 for m in MONTHS_SAID.finditer(said)}
            if months in named | {int(x.group(1)) for x in BARE_NUM.finditer(said)} or \
                    upsell_choice(said, offered) == months:
                return None
            return t.strip().split("\n")[-1]
        if who == "client":
            tail.append(t)
    return None


def upsell_text(months: int, rows: dict[int, dict], targets: list[int], cut: int) -> str:
    """rows — {срок: {"price", "gifts", "raffle"}}, cut — скидка в ₽ (0 — без неё). Цены и «за месяц» — кодом."""
    def line(m: int) -> str:
        p = rows[m]["price"] - cut
        return f"{m} мес — {money(p)} ₽{' со скидкой' if cut else ''} ({money(round(p / m))} ₽/мес)"

    def perks(m: int) -> str:
        r, c = rows[m], rows[months]
        if r["raffle"] and not c["raffle"]:
            return " + игра в подарок и участие в розыгрыше 🎁" if not c["gifts"] else " + участие в розыгрыше"
        return " + игра в подарок 🎁" if r["gifts"] and not c["gifts"] else ""

    # срок клиент уже назвал — не «На какой срок оформляем?» (22.10: выглядело как тот же вопрос о сроке)
    ask = f"Оформляем на {' или '.join(map(str, targets))} мес или оставим {months}?"
    base = per_month(rows[months]["price"] - cut, months)
    cheaper = all(per_month(rows[m]["price"] - cut, m) < base for m in targets)
    return "\n".join([line(months), "", UPSELL_HEAD if cheaper else UPSELL_HEAD_PERK] +
                     [line(m) + perks(m) for m in targets] + ["", ask])


def money(n: int) -> str:
    return f"{n:,}".replace(",", " ")


ATTACH = {"image": "фото", "voice": "голосовое", "file": "файл", "video": "видео", "location": "геолокация",
          "link": "ссылка", "item": "объявление"}


def readable(text: str | None, has_images: bool = False) -> str:
    """«<image>» и т.п. — заглушки сообщений без текста: в алерте по-русски, а фото не упоминаем, если оно приложено."""
    out = []
    for p in (text or "").split(" / "):
        m = re.fullmatch(r"<(\w+)>", p.strip())
        if not m:
            out.append(p)
        elif not (m[1] == "image" and has_images):
            out.append(f"[{ATTACH.get(m[1], m[1])}]")
    return " / ".join(x for x in out if x.strip())


def shows_price(text: str, price: str) -> bool:
    """Сообщение продавца с основным прайсом (первый ответ или {прайс}), где скидка ещё не названа ценой."""
    head = price.strip().split("\n")[0] if price else ""
    return bool(text) and (PRICE_TAIL in text or (head and head in text)) and "со скидкой" not in text


