def is_ack(text: str) -> bool:
    """Только «ок / спасибо / всё понял / 👍» — без вопроса и просьбы."""
    if not text.strip() or "?" in text:
        return False
    return all(w in ACK_WORDS for w in _norm(text).split())   # одни эмодзи — тоже подтверждение


def needs_answer(history: list[tuple[str, str]]) -> bool | None:
    """Ждёт ли клиент ответа: False — последнее слово за продавцом или клиент только поблагодарил/подтвердил
    после продавца без вопроса; True — есть «?»; None — не ясно (спросить LLM)."""
    if not history or history[-1][0] == "seller":
        return False
    tail = []
    for who, t in reversed(history):
        if who == "seller":
            break
        tail.append(t)
    asked = next((t for who, t in reversed(history) if who == "seller"), "")
    # «ок» после названной цены — согласие купить, а не «спасибо» (09.10: бот молчал); после реквизитов — молчим
    offer = OFFER.search(asked) and "Сумма:" not in asked
    if all(is_ack(t) for t in tail) and "?" not in asked and not offer:
        return False
    return True if any("?" in t for t in tail) else None


