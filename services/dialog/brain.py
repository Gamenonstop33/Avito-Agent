def upsell_choice(said: str, offered: list[int]) -> int | None:
    """Ответ на предложение срока больше (offered[0] — срок, который клиент выбрал сам): назвал срок из
    предложенных — его; «нет / оставим» — свой; «да / давайте» при одном варианте — предложенный. Иначе None."""
    if not offered or TERM_PRICE_Q.search(said) or re.search(r"(?i)подума|позже|потом|завтра|дорог", said):
        return None
    m = MONTHS_SAID.search(said)
    nums = [int(m.group(1)) if m.group(1) else 6 if m.group(2) else 12] if m else \
        [int(x) for x in re.findall(r"(?<!\d)(\d{1,2})(?!\d)", said)]
    if nums:
        return nums[0] if len(nums) == 1 and nums[0] in offered else None
    if KEEP_TERM.search(said):
        return offered[0]
    return offered[1] if plain_consent(said) and len(offered) == 2 else None


def plain_consent(said: str) -> bool:
    """Просто согласие («да», «ок, давай», «давайте с подарком»), а не «хочу Hogwarts Legacy в подарок» (стенд 22.10:
    выбор подарка после допродажи сошёл за «да» — счёт на 20 мес)."""
    rest = [w for w in _norm(said).split() if w not in FILLER and not CONSENT.fullmatch(w)]
    return bool(CONSENT.search(said)) and len(rest) <= 3 and not LATIN_WORD.search(said)


