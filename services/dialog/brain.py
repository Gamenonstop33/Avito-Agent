def parse_decision(raw: str) -> Decision:
    """Ответ LLM → решение. Не JSON-объект — ValueError (think спросит ещё раз); поле не того типа — как пустое
    (стенд 22.10: "handoff": "payment" или список вместо объекта роняли ответ клиенту)."""
    d = json.loads(raw or "")
    if not isinstance(d, dict):
        raise ValueError("ответ нейросети — не JSON-объект")
    h = d.get("handoff") if isinstance(d.get("handoff"), dict) else None
    if h:
        reason = h.get("reason") if isinstance(h.get("reason"), str) and h.get("reason") in REASONS else "nonstandard"
        h = {"reason": reason, "summary": h["summary"] if isinstance(h.get("summary"), str) else None}
    reply = (d.get("reply") if isinstance(d.get("reply"), str) else "").replace("{приветствие}", "").strip()
    if h and h["reason"] == "bot_question":
        reply = re.sub(r"(?i)^(нет|да)\b[\s,.!—–-]*", "", reply)   # «Нет, …» — уже ответ на «вы бот?»
        reply = reply[:1].upper() + reply[1:]
        if not reply or BOT_WORDS.search(reply) or MANAGER_CLAIM.search(reply):
            reply = random.choice(BOT_JOKES)
    kb = d.get("kb") if isinstance(d.get("kb"), str) and d["kb"] in CLASSES and d["kb"] != "core" else None
    o = d.get("order")
    try:
        order = {"product": o["product"], "months": int(o["months"]), "price": int(o["price"])} if o else None
    except (KeyError, TypeError, ValueError):
        order = None
    if order and (not isinstance(order["product"], str) or order["product"] not in NAMES):
        order = None
    games = d.get("games") if isinstance(d.get("games"), list) else []
    games = [g.strip()[:80] for g in games if isinstance(g, str) and g.strip()][:5]
    return Decision(reply, h, d.get("stage") if isinstance(d.get("stage"), str) else None, kb, order, games)


def _sentences(text: str) -> list[str]:
    out: list[str] = []
    for s in re.split(r"(?<=[.!?…])\s+|\n+", text):
        if out and not _norm(s):
            out[-1] += " " + s.strip()  # одиночный эмодзи — хвост предыдущей фразы
        elif out and out[-1].endswith(".") and re.match(r"[a-zа-яё]", s.strip()):
            out[-1] += " " + s.strip()  # «доп. аккаунт», «6 мес. на консоль» — сокращение, а не конец фразы (аудит 20.10)
        elif s.strip():
            out.append(s.strip())
    return out


def _norm(s: str) -> str:
    return " ".join(re.sub(r"[^\w]+", " ", s.lower()).split())


def drop_repeats(reply: str, history: list[tuple[str, str]], last: int = 12) -> str:
    """Убирает повторный вопрос-предложение («Вам на 2 месяца за 990₽ подключаем?»), который продавец уже задавал
    (владелец: «без повторов»). Ответы по сути не трогаем — клиент мог переспросить; короткие («Готовы?») — тоже.
    Если повторы — весь ответ, оставляем как есть, чтобы не молчать."""
    said = [_norm(s) for who, t in history[-last:] if who == "seller" for s in _sentences(t)]
    parts = _sentences(reply)
    keep = [s for s in parts if "?" not in s or len(_norm(s)) < 20 or
            not any(SequenceMatcher(None, _norm(s), p).ratio() >= 0.75 for p in said)]
    return " ".join(keep) if keep and len(keep) < len(parts) else reply


