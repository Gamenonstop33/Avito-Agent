SKIP_SECTIONS = ("Прайс", "Почему не купили")


def load_kb(cls: str = "core") -> str:
    """Раздел базы знаний без прайса-снимка (цены берём живые из БД) и без аналитики. Нет файла — пусто."""
    path = ROOT / "knowledge" / f"kb_{cls}.md"
    if not path.exists():
        return ""
    parts = re.split(r"(?m)^(?=## )", path.read_text(encoding="utf-8"))
    return "".join(p for p in parts[1:] if not p[3:].startswith(SKIP_SECTIONS)).strip()


