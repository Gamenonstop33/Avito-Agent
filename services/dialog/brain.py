def price_terms(price: str) -> tuple[set[int], set[int]]:
    """(сроки консоли, сроки ПК) из текста прайса."""
    secs: dict[str, set[int]] = {}
    for block in price.split("\n\n"):
        head = block.strip().split("\n")[0].lower()
        kind = "консоль" if "консол" in head else "ПК" if re.search(r"(?<!\w)(пк|pc)(?!\w)", head) else None
        if kind:
            secs[kind] = {int(m) for m in re.findall(r"(?m)^(\d+) мес", block)}
    return secs.get("консоль", set()), secs.get("ПК", set())


def terms_hint(price: str) -> str:
    """Какие сроки есть и для консоли, и для ПК — по ним бот обязан спросить платформу (считаем кодом из прайса)."""
    c, p = price_terms(price)
    if not c or not p:
        return ""
    fmt = lambda xs: ", ".join(map(str, sorted(xs))) or "—"   # noqa: E731
    return (f"\n\nСРОКИ: {fmt(c & p)} мес — есть и для консоли, и для ПК: если из переписки не ясно, для чего, — цену "
            f"НЕ называй, сначала спроси «На консоль или на ПК?». Только для ПК: {fmt(p - c)} мес — просят такой срок "
            f"(или меньше {min(c)} мес) — скажи, что он есть только для ПК, назови цену, а для консоли — от {min(c)} мес "
            f"(база знаний про «минимум» — только о консоли). Только для консоли: {fmt(c - p)} мес.")


