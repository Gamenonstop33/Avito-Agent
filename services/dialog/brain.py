def parse_decision(raw: str) -> Decision:
    d = json.loads(raw)
    h = d.get("handoff") or None
    if h and h.get("reason") not in REASONS:
        h["reason"] = "nonstandard"
    reply = (d.get("reply") or "").replace("{приветствие}", "").strip()
    if h and h["reason"] == "bot_question":
        reply = re.sub(r"(?i)^(нет|да)\b[\s,.!—–-]*", "", reply)   # «Нет, …» — уже ответ на «вы бот?»
        reply = reply[:1].upper() + reply[1:]
        if not reply or BOT_WORDS.search(reply):
            reply = random.choice(BOT_JOKES)
    kb = d.get("kb") if d.get("kb") in CLASSES and d.get("kb") != "core" else None
    o = d.get("order")
    try:
        order = {"product": o["product"], "months": int(o["months"]), "price": int(o["price"])} if o else None
    except (KeyError, TypeError, ValueError):
        order = None
    if order and order["product"] not in NAMES:
        order = None
    games = [g.strip()[:80] for g in d.get("games") or [] if isinstance(g, str) and g.strip()][:5]
    return Decision(reply, h, d.get("stage"), kb, order, games)


def _sentences(text: str) -> list[str]:
    out: list[str] = []
    for s in re.split(r"(?<=[.!?…])\s+|\n+", text):
        if out and not _norm(s):
            out[-1] += " " + s.strip()  # одиночный эмодзи — хвост предыдущей фразы
        elif s.strip():
            out.append(s.strip())
    return out


def _norm(s: str) -> str:
    return " ".join(re.sub(r"[^\w]+", " ", s.lower()).split())


def drop_repeats(reply: str, history: list[tuple[str, str]], last: int = 12) -> str:
    """Убирает повторный вопрос-предложение («Вам на 2 месяца за 990₽ подключаем?»), который продавец уже задавал
    (владелец: «без повторов»). Ответы по сути не трогаем — клиент мог переспросить; короткие («Готовы?») — тоже.
    Если повторы — весь ответ, оставляем как есть, чтобы не молчать."""
    said = [_norm(s) for who, t in history[-last:] if who == "seller" for s in _sentences(t)]
    parts = _sentences(reply)
    keep = [s for s in parts if "?" not in s or len(_norm(s)) < 20 or
            not any(SequenceMatcher(None, _norm(s), p).ratio() >= 0.75 for p in said)]
    return " ".join(keep) if keep and len(keep) < len(parts) else reply


