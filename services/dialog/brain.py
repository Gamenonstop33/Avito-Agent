def term_only(said: str) -> bool:
    if TERM_PRICE_Q.search(said):
        return False
    words = _norm(BARE_NUM.sub(" ", re.sub(r"(?i)(?<!\d)\d{1,2}\s*(мес\w*|м(?!\w))|пол\s*года|(?<!\w)год\w*", " ",
                                           said))).split()
    return bool(MONTHS_SAID.search(said) or BARE_NUM.search(said)) and all(w in FILLER for w in words)


def implied_order(history: list[tuple[str, str]], prices: dict[str, dict[int, int]]) -> dict | None:
    """Клиент согласился («давай 3 месяца», «ок» после цены) или после прайса просто назвал срок, а LLM не оформила
    заказ. Срок — из слов клиента или единственная цена в последнем сообщении продавца (не ясно — срок, который клиент
    называл до этого); тип — единственный раздел прайса с этим сроком или явное «консоль»/«ПК» клиента; личный
    аккаунт — только если клиент о нём говорил. Не ясно или есть вопрос — None."""
    tail = []
    for who, t in reversed(history):
        if who == "seller":
            break
        tail.append(t)
    said = " ".join(reversed(tail))
    asked = next((t for who, t in reversed(history) if who == "seller"), "")
    # предложение срока больше — последним или перед коротким переспросом «На какой срок оформляем?» (прогон 21.10:
    # после переспроса «оставим 2» уже не считалось ответом на допродажу)
    upsold = next((t for who, t in history[-6:][::-1] if who == "seller" and UPSELL_MARK in t), "")
    offered: list[int] = []
    if tail and upsold and (UPSELL_MARK in asked or len(asked) < 80):   # ответ на предложение срока больше
        offered = offered_terms(upsold)
        months = upsell_choice(said, offered)
        if not months:
            return None
    else:
        chose = bool(asked) and TERM_ASKED.search(asked) and term_only(said)
        if not tail or NOT_NOW.search(said) or not (CONSENT.search(said) or chose):
            return None
        if any("?" in t and not NUDGE.match(t) and not PAY_Q.search(t) for t in tail) or ASKS.search(said):
            return None   # клиент о чём-то спрашивает («да, а игры какие?») — пусть отвечает LLM
        m = MONTHS_SAID.search(said)
        bare = [int(x.group(1)) for x in BARE_NUM.finditer(said)]
        terms = {t for rows in prices.values() for t in rows}
        if m:
            months = int(m.group(1)) if m.group(1) else 6 if m.group(2) else 12
        elif len(bare) == 1 and bare[0] in terms:   # «давайте 10 на пк» — число без «мес» (прогон 15.10)
            months = bare[0]
        else:
            quoted = {int(x) for x in PRICE_LINE.findall(asked)}
            # «ок» на ответ, где кроме названного срока целиком прайс, — срок, который клиент назвал раньше
            before = [x for who, t in history[-8:-len(tail)] if who == "client" for x in MONTHS_SAID.finditer(t)]
            prev = before and (int(before[-1].group(1)) if before[-1].group(1) else 6 if before[-1].group(2) else 12)
            if len(quoted) == 1:
                months = quoted.pop()
            elif prev and not bare and (prev in quoted or not quoted or PC_TERMS_HEAD in asked):
                # «давайте» на условия ПК (там прайс на личный) или на ответ без цен — срок, названный перед этим;
                # «давайте 7» — такого срока нет, прошлым не подменяем
                months = prev
            else:
                return None
    client = " ".join(t for who, t in history[-12:] if who == "client")
    # «и на xbox, и на пк» — это личный аккаунт (прогон 21.10: после прайса на личный «давайте на 6» ушло на консоль)
    offer_own = bool(re.search(r"(?i)на\s+ваш\s+(личн\w*\s+)?аккаунт", asked)) and months in prices.get("personal", {})
    if PERSONAL_WORDS.search(client) or BOTH_PLATFORMS.search(client):
        cands = [p for p in prices if p == "personal" and months in prices[p]]
    else:
        cands = [p for p in prices if p != "personal" and months in prices[p]]
        pc, console = bool(PC_WORDS.search(client)), bool(CONSOLE_WORDS.search(client))
        if len(cands) > 1 and pc != console:
            cands = [p for p in cands if p == ("pc" if pc else "console")]
        if len(cands) > 1 and offered:   # допродажа была на один тип: 12 → 20 — консоль (ПК 12 мес нет)
            cands = [p for p in cands if all(t in prices[p] for t in offered)]
        if offer_own and not PC_WORDS.search(said) and not CONSOLE_WORDS.search(said):
            return None   # предложили и личный, а клиент не уточнил — пусть решает LLM
    if len(cands) != 1:
        return None
    return {"product": cands[0], "months": months, "price": prices[cands[0]][months]}


