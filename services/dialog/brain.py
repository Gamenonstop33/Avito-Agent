def answer_part(reply: str) -> str:
    """Ответ LLM на вопрос клиента без того, что скажет код (цены, сроки, реквизиты, «оформляем?»): клиент спросил
    и выбрал срок — сначала ответ, потом допродажа (прод 16.10: на «По qr?» ушла одна допродажа)."""
    keep = [s for s in _sentences(reply or "") if "₽" not in s and not ASK_GO.search(s)
            and not re.search(r"(?i)реквизит|\d+\s*мес|^(отлично|хорошо|супер|принято)[!.,]*$", s)]
    return " ".join(keep)


