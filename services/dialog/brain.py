# 09.10: «давай 3 месяца» → LLM повторила цену, «ок» → молчание, «ну и?» → «оплачиваете?»; ссылка — только после
# «присылай уже». Срок и тип однозначны — заказ оформляет код, без переспросов.
CONSENT = re.compile(r"(?i)(?<!\w)(да|ок|оке?й?|ok|давай\w*|беру|возьму|оформ\w*|хорошо|ладно|го|погнали|согласн\w*|"
                     r"продл\w*|хочу|"
                     r"подходит|устраивает|присыла\w*|скида\w*|кида\w*|реквизит\w*|оплачу|плачу)(?!\w)|"
                     r"как\s+(оплатить|платить)|куда\s+(платить|переводить|оплачивать)")
NOT_NOW = re.compile(r"(?i)(?<!\w)не(?!\w)|подума|дорог|позже|потом|завтра|отказ")
NUDGE = re.compile(r"(?i)^\s*(ну|и|ау|алло|ну\s+и|и\s+что|и\s+дальше|дальше|жду|ну\s+что)\s*[?!.…]*\s*$")
PAY_Q = re.compile(r"(?i)как\s+(оплатить|платить)|куда\s+(платить|переводить|оплачивать)|реквизит|ссылк|присыла")
MONTHS_SAID = re.compile(r"(?i)(?<!\d)(\d{1,2})\s*(?:мес|месяц|м(?!\w))|(полгода)|(?<!\w)(год)(?!\w)")
PRICE_LINE = re.compile(r"(?<!\d)(\d{1,2})\s*мес\w*\.?\s*[—–-]\s*\d[\d\s]*₽")
PC_WORDS = re.compile(r"(?i)(?<!\w)(пк|pc|компьютер\w*|ноутбук\w*|ноут)(?!\w)")
CONSOLE_WORDS = re.compile(r"(?i)консол\w*|xbox|иксбокс|series|(?<!\w)one(?!\w)")
PERSONAL_WORDS = re.compile(r"(?i)личн\w*\s+акк|на\s+(мой|свой|моём|своём)\s+акк|мой\s+аккаунт")
ORDER_LEAD = "Отлично!"


def implied_order(history: list[tuple[str, str]], prices: dict[str, dict[int, int]]) -> dict | None:
    """Клиент согласился («давай 3 месяца», «ок» после цены), а LLM не оформила заказ. Срок — из слов клиента или
    единственная цена в последнем сообщении продавца; тип — единственный раздел прайса с этим сроком или явное
    «консоль»/«ПК» клиента; личный аккаунт — только если клиент о нём говорил. Не ясно или есть вопрос — None."""
    tail = []
    for who, t in reversed(history):
        if who == "seller":
            break
        tail.append(t)
    said = " ".join(reversed(tail))
    asked = next((t for who, t in reversed(history) if who == "seller"), "")
    if tail and UPSELL_HEAD in asked:   # ответ на предложение срока больше
        months = upsell_choice(said, [int(x) for x in PRICE_LINE.findall(asked)])
        if not months:
            return None
    else:
        if not tail or NOT_NOW.search(said) or not CONSENT.search(said):
            return None
        if any("?" in t and not NUDGE.match(t) and not PAY_Q.search(t) for t in tail):
            return None   # клиент о чём-то спрашивает («да, а игры какие?») — пусть отвечает LLM
        m = MONTHS_SAID.search(said)
        if m:
            months = int(m.group(1)) if m.group(1) else 6 if m.group(2) else 12
        else:
            quoted = {int(x) for x in PRICE_LINE.findall(asked)}
            if len(quoted) != 1:
                return None
            months = quoted.pop()
    client = " ".join(t for who, t in history[-12:] if who == "client")
    if PERSONAL_WORDS.search(client):
        cands = [p for p in prices if p == "personal" and months in prices[p]]
    else:
        cands = [p for p in prices if p != "personal" and months in prices[p]]
        pc, console = bool(PC_WORDS.search(client)), bool(CONSOLE_WORDS.search(client))
        if len(cands) > 1 and pc != console:
            cands = [p for p in cands if p == ("pc" if pc else "console")]
    if len(cands) != 1:
        return None
    return {"product": cands[0], "months": months, "price": prices[cands[0]][months]}


