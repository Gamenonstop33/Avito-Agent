def pay_only(ip_on: bool, ip_only: bool = False) -> str:
    if ip_only:
        return "Оплата только по ссылке СБП — с любого российского банка."
    return ("Оплата только переводом по реквизитам" + (" или по ссылке СБП" if ip_on else "") +
            " — с любого российского банка.")


def pay_guard(reply: str, client_text: str, ip_on: bool, ip_only: bool = False) -> str:
    """«С зарубежной карты / PayPal / криптой можно?» — «да» LLM неверно: платим только переводом на банк из
    реквизитов или (если включено) по ссылке СБП на ИП (решение 21.10). QR без ИП — тоже нет. ip_only — «🏦 Только
    ИП»: «на карту» — нет."""
    if FOREIGN_PAY.search(client_text) and not REFUSED.search(reply):
        return pay_only(ip_on, ip_only)
    if ip_only and CARD_TO.search(client_text) and not REFUSED.search(reply):
        return IP_ONLY_REPLY
    if QR_ASK.search(client_text) and not ip_on and not REFUSED.search(reply):
        return "По QR не получится — оплата переводом по номеру из реквизитов, с любого российского банка."
    return reply


def night_guard(reply: str) -> str:
    """Ночью без автовыдачи «подключим сразу / ночью / в любое время» — неправда: «как можно оперативнее»."""
    if not NIGHT_PROMISE.search(reply):
        return reply
    keep = [s for s in _sentences(reply) if not NIGHT_PROMISE.search(s)]
    return " ".join(dict.fromkeys(keep + ["Подключим как можно оперативнее 🙏"]))
