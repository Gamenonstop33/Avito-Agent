def is_duplicate(text: str, said: list[str], ratio: float = 0.85) -> bool:
    """Почти дословный повтор недавнего сообщения продавца (в т.ч. удалённого Максом) — не отправляем."""
    n = _norm(text)
    return len(n) >= 15 and any(SequenceMatcher(None, n, _norm(s)).ratio() >= ratio for s in said if s)

