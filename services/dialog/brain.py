def is_duplicate(text: str, said: list[str], ratio: float = 0.85) -> bool:
    """Почти дословный повтор недавнего сообщения продавца (в т.ч. удалённого Максом) — не отправляем. Новое число или
    латинское слово (игра, срок, цена) — уже не повтор (стенд 22.10: «Да, UFC 5 есть…» после «Да, NHL 25 есть…»)."""
    n = _norm(text)
    keys = set(re.findall(r"[a-z0-9]+", n))
    return len(n) >= 15 and any(SequenceMatcher(None, n, m).ratio() >= ratio and keys <= set(re.findall(r"[a-z0-9]+", m))
                                for m in map(_norm, filter(None, said)))

