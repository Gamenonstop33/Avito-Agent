def upsell_targets(product: str, months: int, terms) -> list[int]:
    """Какие сроки предложить вместо выбранного; лесенки нет (личный аккаунт) — ближайший чётный срок больше."""
    ladder = UPSELL.get(product)
    if ladder is None:
        return [t for t in sorted(terms) if t > months and t % 2 == 0][:1]
    return [t for t in ladder.get(months, ()) if t in terms]


def per_month(price: int, months: int) -> int:
    return round(price / months)


def worth(months: int, rows: dict[int, dict], target: int, cut: int = 0) -> bool:
    """Срок больше стоит предлагать: за месяц дешевле или добавляет подарок / розыгрыш (аудит 20.10: 10 → 12 мес
    «выгоднее» при тех же 349 ₽/мес; ПК 10 → 20 — дороже за месяц)."""
    r, c = rows[target], rows[months]
    cheaper = per_month(r["price"] - cut, target) < per_month(c["price"] - cut, months)
    return cheaper or (r["gifts"] and not c["gifts"]) or (r["raffle"] and not c["raffle"])


