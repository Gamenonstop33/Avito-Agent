def goods_guard(reply: str, handoff: dict | None, games: list[str], client_text: str, personal: bool = False,
                context: str = "") -> tuple[str, dict | None]:
    """PS Plus и возврат — всегда владельцу; чужой товар, который LLM предлагает «продать отдельно» (не игра — games
    пуст), и «да, есть — уточню» при передаче — «Уточню и напишу Вам» без да/нет (прогон 20.10: Netflix, YouTube).
    Оплату и вход по коду не перебиваем."""
    if handoff and handoff.get("reason") in ("payment", "code"):
        return reply, handoff
    if PS_ASK.search(client_text):
        return GOODS_HANDOFF, {"reason": "nonstandard", "summary": "спрашивает про PS Plus / подписку PlayStation"}
    if REFUND_ASK.search(client_text) or REFUND_PROMISE.search(reply):   # «а если не подключится?» — «вернём»
        return GOODS_HANDOFF, {"reason": "nonstandard", "summary": "спрашивает про возврат денег"}
    if personal and CREDS_REQUEST.search(reply):   # личный аккаунт: данные запрашивает владелец после оплаты (06.10)
        return "Данные аккаунта запросим после оплаты — здесь, в чате.", handoff
    if FOREIGN_ASK.search(client_text) and not games:
        return GOODS_HANDOFF, handoff or {"reason": "nonstandard", "summary": "спрашивает про товар не из прайса"}
    # покупка игр, ключей и Steam — через владельца (решение 21.10): бот не собирает логин и не переспрашивает
    if not handoff and (STEAM_BUY.search(client_text) or BUY_GAME.search(client_text) or (
            BUY_WORD.search(client_text) and not SUB_WORDS.search(client_text)
            and (games or SALE_PROMISE.search(reply)))):
        return GAME_HANDOFF, {"reason": "game", "summary": "хочет купить: " + client_text[:120]}
    if not handoff and not games and OFFER_SALE.search(reply):
        return GOODS_HANDOFF, {"reason": "nonstandard", "summary": "спрашивает про товар не из прайса"}
    if handoff and handoff.get("reason") == "nonstandard" and (YES_HAVE.search(reply) or re.search(r"(?i)уточн", reply)):
        return GOODS_HANDOFF, handoff   # «Netflix не продаём. Уточню…» — без «да/нет», только «уточню»
    if CHANGE_CREDS.search(client_text) and not OWN_ACCOUNT.search(client_text) and \
            not STEAM_CTX.search(f"{context} {client_text}") and re.search(r"(?i)^\s*да(?!\w)|можно", reply):
        # решение 21.10: пароль и почту выданной учётки менять нельзя (LLM отвечала «да»; Макс 06.02 — «Нет»);
        # Steam и игры на аккаунте клиента — другое: там Макс отвечал «можно, через сутки»
        return CREDS_NO, handoff
    if CONTACT.search(reply):   # контакты вне Avito в чате не даём (решение 21.10)
        reply = " ".join(s for s in _sentences(reply) if not CONTACT.search(s)) or CONTACTS_NO
    return reply, handoff


