"""Маскировка персональных данных и доступов: карты, почты, пароли, телефоны, коды (без сети и БД)."""
import re

MASKS = [
    (re.compile(r"\b\d{4}[ -]?\d{4}[ -]?\d{4}[ -]?\d{4}(?:[ -]?\d{1,3})?\b"), "<карта>"),
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+\s*[:;|]\s*\S+"), "<почта>:<скрыто>"),   # почта:пароль
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+"), "<почта>"),
    (re.compile(r"<почта>[^\w<]{0,6}(?=\S*\d)\S+"), "<почта> <скрыто>"),   # почта 💚 пароль
    (re.compile(r"(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}"), "<телефон>"),
    (re.compile(r"(?i)(парол\w*|password)(\s*[:\-–—]?\s*)\S+"), r"\1\2<скрыто>"),
    (re.compile(r"(?i)(логин\w*|login|код\w*)(\s*[:\-–—]?\s*)(?=\S*\d)\S+"), r"\1\2<скрыто>"),
]


def mask(text: str) -> str:
    for rx, repl in MASKS:
        text = rx.sub(repl, text)
    return text
